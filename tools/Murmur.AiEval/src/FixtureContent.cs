using Murmur.Core.Transcription;

namespace Murmur.AiEval;

/// <summary>A fact planted at a known time, optionally asked about.</summary>
/// <param name="Stems">Lower-case substrings that must appear in this fact's segment only (keeps it unambiguous).</param>
/// <param name="Question">Paraphrased question, or <c>null</c> when the fact is only a distractor.</param>
/// <param name="Keywords">Search-box words for the keyword-only retrieval check; they occur in the fact sentence.</param>
/// <param name="AnswerStems">
/// Extra lower-case substrings that also show an answer conveys the fact (digits a model may write instead of the
/// spelled-out words); unlike <paramref name="Stems"/> they need not be unique in the transcript.
/// </param>
public sealed record PlantedFact(
    string Id,
    TimeSpan At,
    Speaker Speaker,
    string Text,
    IReadOnlyList<string> Stems,
    string? Question,
    string? Keywords,
    IReadOnlyList<string>? AnswerStems = null)
{
    /// <summary><see cref="Stems"/> followed by <see cref="AnswerStems"/>: any of them in an answer means it states the fact.</summary>
    public IReadOnlyList<string> AllAnswerStems => AnswerStems is null ? Stems : [.. Stems, .. AnswerStems];
}

/// <summary>A question the recording cannot answer; <paramref name="Stems"/> must not occur anywhere.</summary>
public sealed record UnanswerableQuestion(string Question, string Keywords, IReadOnlyList<string> Stems);

/// <summary>A product area in the grammatical cases the filler templates need.</summary>
public sealed record Feature(string Nominative, string Accusative, string Genitive, string AfterPo);

/// <summary>A colleague; <paramref name="PastEnding"/> completes past-tense verbs (обіця-в / обіця-ла).</summary>
public sealed record Person(string Nominative, string Genitive, string Instrumental, string PastEnding);

